#!/usr/bin/env bash
# A throwaway CA and a server certificate for 10.0.2.2 (the emulator's host),
# made fresh for each e2e run, and the debug-only trust in it.
#
# The trust lives in app/src/debug (gitignored, generated here only): a
# network security config whose debug-overrides trust the CA. debug-overrides
# apply only to a debuggable build, and src/debug is not part of a release
# build, so a release trusts nothing of this.
set -euo pipefail
OUT=${1:-e2e/out}
mkdir -p "$OUT"
openssl req -x509 -newkey rsa:2048 -nodes -sha256 -days 3 -subj "/CN=haus e2e CA" \
  -addext "basicConstraints=critical,CA:TRUE" -addext "keyUsage=critical,keyCertSign,cRLSign" \
  -keyout "$OUT/ca.key" -out "$OUT/ca.pem"
openssl req -newkey rsa:2048 -nodes -sha256 -subj "/CN=10.0.2.2" -keyout "$OUT/server.key" -out "$OUT/server.csr"
printf 'subjectAltName=IP:10.0.2.2,IP:127.0.0.1\nbasicConstraints=CA:FALSE\nkeyUsage=critical,digitalSignature,keyEncipherment\nextendedKeyUsage=serverAuth\n' > "$OUT/ext.cnf"
openssl x509 -req -sha256 -days 3 -in "$OUT/server.csr" -CA "$OUT/ca.pem" -CAkey "$OUT/ca.key" \
  -CAcreateserial -extfile "$OUT/ext.cnf" -out "$OUT/server.pem"

D=app/src/debug
mkdir -p "$D/res/raw" "$D/res/xml"
cp "$OUT/ca.pem" "$D/res/raw/e2e_ca.pem"
cat > "$D/res/xml/network_security_config.xml" <<'XML'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by e2e/make_ca.sh, debug builds only. -->
<network-security-config>
    <debug-overrides>
        <trust-anchors>
            <certificates src="@raw/e2e_ca" />
            <certificates src="system" />
        </trust-anchors>
    </debug-overrides>
</network-security-config>
XML
cat > "$D/AndroidManifest.xml" <<'XML'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by e2e/make_ca.sh, debug builds only. -->
<manifest xmlns:android="http://schemas.android.com/apk/res/android">
    <application android:networkSecurityConfig="@xml/network_security_config" />
</manifest>
XML
echo "CA and server certificate in $OUT; debug trust in $D"
